exception when duplicate_object then null; end $$;
do $$ begin create type public.lot_status as enum ('disponible','agotado','vencido','bloqueado');
exception when duplicate_object then null; end $$;
do $$ begin create type public.movement_type as enum ('entrada_compra','ajuste_positivo','salida_venta','reserva','liberacion_reserva','merma','ajuste_negativo','devolucion','traslado','proceso_consumo','proceso_produccion');
