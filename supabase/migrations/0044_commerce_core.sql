  company_id uuid not null references public.companies(id) on delete cascade,
  name text not null, description text, sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  unique (company_id, name)
);

create table if not exists public.fish_species (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  common_name text not null, scientific_name text, family text, notes text,
  status public.entity_status not null default 'activo',
  created_at timestamptz not null default now(),
  unique (company_id, common_name)
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  sku text, name text not null,
  species_id uuid references public.fish_species(id) on delete set null,
  category_id uuid references public.product_categories(id) on delete set null,
  presentation text,
  base_unit public.unit_measure not null default 'kg',
  package_format text, package_weight numeric(12,3),
  min_stock numeric(12,3) not null default 0,
  sale_price numeric(12,2) not null default 0,
  last_cost numeric(12,2) not null default 0,
  avg_cost  numeric(12,2) not null default 0,
