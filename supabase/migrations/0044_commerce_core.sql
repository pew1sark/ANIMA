-- ---------- NUMERACIÓN POR EMPRESA ----------
create table if not exists public.counters (
  company_id uuid not null references public.companies(id) on delete cascade,
  key   text   not null,
  value bigint not null default 0,
  primary key (company_id, key)
);

create or replace function public.next_code(p_company uuid, p_prefix text)
returns text language plpgsql security definer set search_path = public, pg_temp as $$
declare v_year text := to_char(now() at time zone 'America/Santiago','YYYY'); v_val bigint;
begin
  insert into public.counters (company_id, key, value) values (p_company, p_prefix||'-'||v_year, 1)
  on conflict (company_id, key) do update set value = public.counters.value + 1
  returning value into v_val;
  return p_prefix||'-'||v_year||'-'||lpad(v_val::text, 6, '0');
end $$;
revoke execute on function public.next_code(uuid,text) from public, anon;
grant  execute on function public.next_code(uuid,text) to authenticated;

