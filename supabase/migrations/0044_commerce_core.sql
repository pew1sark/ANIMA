-- ---------- RLS ----------
-- Operación (catálogo, inventario): empleado (40).
-- Dinero (compras, registro tributario): encargado (60).
do $$
declare t text; lvl int;
begin
  foreach t in array array['product_categories','fish_species','products','product_price_history',
                           'locations','suppliers','supplier_aliases','supplier_products',
                           'inventory_lots','inventory_movements','counters',
                           'purchases','purchase_items','purchase_history'] loop
    lvl := case when t in ('purchases','purchase_items','purchase_history') then 60 else 40 end;
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %I on public.%I', t||'_company', t);
    execute format($p$create policy %I on public.%I for all to authenticated
      using (public.has_company_level(company_id, %s))
      with check (public.has_company_level(company_id, %s))$p$, t||'_company', t, lvl, lvl);
  end loop;
end $$;
