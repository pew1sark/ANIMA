-- ---------- CÓDIGOS AUTOMÁTICOS POR EMPRESA ----------
create or replace function public.set_lot_code()
returns trigger language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if new.code is null then new.code := public.next_code(new.company_id, 'LOTE'); end if;
  return new;
end $$;
create or replace function public.set_purchase_code()
returns trigger language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if new.code is null then new.code := public.next_code(new.company_id, 'COM'); end if;
  return new;
end $$;
revoke execute on function public.set_lot_code()      from public, anon, authenticated;
revoke execute on function public.set_purchase_code() from public, anon, authenticated;

drop trigger if exists inventory_lots_code on public.inventory_lots;
create trigger inventory_lots_code before insert on public.inventory_lots
  for each row execute function public.set_lot_code();
drop trigger if exists purchases_code on public.purchases;
create trigger purchases_code before insert on public.purchases
  for each row execute function public.set_purchase_code();

