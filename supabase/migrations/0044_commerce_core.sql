-- Portado desde JLIZ BUSINESS con tres correcciones multiempresa:
--   1. company_id not null en TODAS las tablas
--   2. los índices únicos pasan a ser POR EMPRESA (sku, códigos, folio SII):
--      si no, el segundo cliente no podría usar un código que ya usó el primero
--   3. la numeración de códigos es por empresa, no global
--
-- Verificado (8/8): dos empresas pueden tener el mismo SKU-001, sus
-- numeraciones arrancan las dos en 000001, y ninguna ve ni escribe
-- en los datos de la otra. Ver supabase/tests/commerce_isolation.sql
